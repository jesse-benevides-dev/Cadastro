    private void botaoConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoConfirmarActionPerformed
        try {

        if (produto == null) {
            produto = new Produto();
        }

        produto.alterarNome(edNome.getText());
        produto.alterarUnidade(edUnidade.getText());
        produto.alterarPreco(Double.parseDouble(
                edPreco.getText().replace(",", ".")));
        produto.alterarQuantidade(Integer.parseInt(edQuantidade.getText()));

        confirmado = true;
        dispose();

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Preencha os campos de preço e quantidade corretamente."
        );
    }
    }//GEN-LAST:event_botaoConfirmarActionPerformed

